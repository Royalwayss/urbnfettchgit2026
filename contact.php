<script>
document.addEventListener("DOMContentLoaded", function () {
$(function () {
    $("#urbnContactForm").validate({
        rules: {
            name: {
                required: true,
                minlength: 2
            },
            email: {
                required: true,
                email: true
            },
            phone: {
                required: true,
                digits: true,
                minlength: 9,
                maxlength: 12
            },
            subject: {
                required: true,
                minlength: 2
            },
            message: {
                required: true,
                minlength: 10
            }
        },
        messages: {
            name: "Please enter your name",
            email: "Please enter a valid email address",
            phone: "Please enter a valid phone number (9-12 digits)",
            subject: "Please enter a subject",
            message: "Please enter a message (min 10 characters)"
        },
        errorElement: "label",
        errorPlacement: function (error, element) {
            error.addClass("urbn-error-label text-danger small");
            element.closest(".mb-4").find(".urbn-error-label").html(error.html() || error.text()).removeClass("d-none");
        },
        highlight: function (element) {
            $(element).addClass("is-invalid");
        },
        unhighlight: function (element) {
            $(element).removeClass("is-invalid");
            $(element).closest(".mb-4").find(".urbn-error-label").addClass("d-none").html("");
        },
        submitHandler: function (form) {
            var $form = $(form);
            var $btn = $("#urbnContactSubmit");
            var $msg = $("#urbn-form-message");

            $btn.prop("disabled", true).text("Sending...");
            $msg.hide();

            $.ajax({
                url: $form.attr("data-action"),
                method: "POST",
                data: $form.serialize(),
                dataType: "json"
            }).done(function (res) {
                if (res.status === "success") {
                    $msg.removeClass("alert-danger").addClass("alert alert-success").text(res.message).show();
                    form.reset();
                } else {
                    $msg.removeClass("alert-success").addClass("alert alert-danger").text(res.message || "Something went wrong. Please try again.").show();
                }
                $msg[0].scrollIntoView({ behavior: "smooth", block: "center" });
                $msg.focus();
            }).fail(function () {
                $msg.removeClass("alert-success").addClass("alert alert-danger").text("Unable to send message right now. Please try again later.").show();
                $msg[0].scrollIntoView({ behavior: "smooth", block: "center" });
                $msg.focus();
            }).always(function () {
                $btn.prop("disabled", false).text("Send");
            });

            return false;
        }
    });
});
});
</script>