 <script>
  

    // 5-Second Rotational Highlighting for Solutions
    document.addEventListener('DOMContentLoaded', () => {
      const solutionItems = document.querySelectorAll('.urbn-newproduct-sec-solution-item');
      const container = document.getElementById('urbnNewProductSecSolutionsContainer');
      let currentIndex = 0;
      let intervalId = null;

      function highlightItem(index) {
        solutionItems.forEach(item => item.classList.remove('is-active'));
        if (solutionItems[index]) {
          solutionItems[index].classList.add('is-active');
        }
      }

      function startCycle() {
        if (intervalId) return;
        intervalId = setInterval(() => {
          currentIndex = (currentIndex + 1) % solutionItems.length;
          highlightItem(currentIndex);
        }, 2000);
      }

      function stopCycle() {
        clearInterval(intervalId);
        intervalId = null;
      }

      // Initial activation
      highlightItem(currentIndex);
      startCycle();

      // Pause automated cycle while user hovers over the section
      if (container) {
        container.addEventListener('mouseenter', stopCycle);
        container.addEventListener('mouseleave', startCycle);
      }
    });
  </script>
