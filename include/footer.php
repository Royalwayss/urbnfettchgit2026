<script>
const buttons = document.querySelectorAll('.urbn-industry-we .nav-link');
const imgEl = document.getElementById('industryImg');
const titleEl = document.getElementById('industryTitle');
const descEl = document.getElementById('industryDesc');
const iconEl = document.getElementById('cardIcon');
const bar = document.getElementById('progressBar');

let current = 0,
    timer;

function setTab(index) {
    current = index;
    buttons.forEach((b, i) => b.classList.toggle('active', i === index));

    imgEl.style.opacity = '0.2';
    setTimeout(() => {
        const btn = buttons[index];
        imgEl.src = btn.dataset.img;
        titleEl.textContent = btn.dataset.title;
        descEl.textContent = btn.dataset.desc;
        iconEl.className = `bi ${btn.dataset.icon} card-icon`;
        imgEl.style.opacity = '1';
    }, 150);

    bar.classList.remove('active');
    void bar.offsetWidth; // Reflow reset
    bar.classList.add('active');
}

const start = () => timer = setInterval(() => setTab((current + 1) % buttons.length), 9000);
const stop = () => {
    clearInterval(timer);
    bar.classList.remove('active');
};

buttons.forEach((btn, i) => btn.onclick = () => setTab(i));
document.getElementById('industryShowcase').onmouseenter = stop;
document.getElementById('industryShowcase').onmouseleave = () => {
    bar.classList.add('active');
    start();
};

start();
</script>


